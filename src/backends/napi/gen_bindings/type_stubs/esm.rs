/// Names the native module exports at runtime, read from the generated declarations: every
/// `class`, `function`, `enum` and `const`. Interfaces and type aliases have no runtime value.
pub(super) fn runtime_export_names(dts: &str) -> Vec<String> {
    let mut names = Vec::new();
    for line in dts.lines() {
        let rest = line
            .strip_prefix("export declare ")
            .or_else(|| line.strip_prefix("export "));
        let Some(rest) = rest else { continue };
        let mut words = rest.split_whitespace();
        let mut kind = words.next();
        if kind == Some("const") {
            let mut ahead = words.clone();
            if ahead.next() == Some("enum") {
                words.next();
                kind = Some("enum");
            }
        }
        if !matches!(kind, Some("class" | "function" | "enum" | "const" | "let" | "var")) {
            continue;
        }
        let Some(word) = words.next() else { continue };
        let name: String = word
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '$')
            .collect();
        if is_esm_export_name(&name) && !names.contains(&name) {
            names.push(name);
        }
    }
    names.sort();
    names
}

/// An export name the ESM wrapper can declare with `export const`.
fn is_esm_export_name(name: &str) -> bool {
    const RESERVED: &[&str] = &[
        "default",
        "class",
        "function",
        "const",
        "let",
        "var",
        "new",
        "delete",
        "import",
        "export",
        "static",
        "enum",
        "await",
        "yield",
        "null",
        "true",
        "false",
        "void",
        "this",
        "super",
        "with",
        "in",
        "of",
        "if",
        "else",
        "for",
        "while",
        "do",
        "switch",
        "case",
        "return",
        "break",
        "continue",
        "try",
        "catch",
        "finally",
        "throw",
        "typeof",
        "instanceof",
        "debugger",
        "extends",
        "implements",
        "interface",
        "package",
        "private",
        "protected",
        "public",
    ];
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && !RESERVED.contains(&name)
}

/// The ESM entry point for `import { name } from "<package>"`.
///
/// Node's CommonJS lexer finds named exports only in `module.exports.name = ...` or
/// `exports.name = ...` statements, so `module.exports = nativeBinding` exposes none. This module
/// imports the CommonJS entry as its default export and re-declares each export by name.
pub(super) fn gen_esm_wrapper(names: &[String], entrypoint: &str) -> String {
    crate::backends::napi::template_env::render(
        "esm_wrapper.mjs.jinja",
        crate::alef_context! { names => names, entrypoint => entrypoint },
    )
}

#[cfg(test)]
mod tests {
    use super::gen_esm_wrapper;

    #[test]
    fn esm_wrapper_preserves_existing_bytes_for_empty_and_named_exports() {
        let cases = [
            (
                Vec::new(),
                "./index.js",
                "// DO NOT EDIT - auto-generated by alef\nimport binding from \"./index.js\";\n\n\nexport default binding;\n",
            ),
            (
                vec!["Client".to_string(), "fetch".to_string()],
                "./index-wrapper.cjs",
                "// DO NOT EDIT - auto-generated by alef\nimport binding from \"./index-wrapper.cjs\";\n\nexport const Client = binding.Client;\nexport const fetch = binding.fetch;\n\nexport default binding;\n",
            ),
        ];
        for (names, entrypoint, expected) in cases {
            assert_eq!(gen_esm_wrapper(&names, entrypoint), expected);
        }
    }
}
